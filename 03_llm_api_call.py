"""### Giving the Bot a memory
##### REAL memory - keep appending to the messages list.
"""

import os
from groq import Groq

client = Groq(api_key=os.environ["GROQ_API_KEY"])
MODEL = "llama-3.3-70b-versatile"

# THIS list is the memory (the "notebook"). It grows every turn.
messages = [{"role": "system", "content": "You are a helpful assistant."}]

# ----- Turn 1 -----
messages.append({"role": "user", "content": "My name is Tanya. Please remember it."})
r1 = client.chat.completions.create(model=MODEL, messages=messages)
answer1 = r1.choices[0].message.content
print("Bot:", answer1)
messages.append({"role": "assistant", "content": answer1})   # write the reply in the notebook!

# ----- Turn 2 ----- (we resend the WHOLE notebook, so the name is still in there)
messages.append({"role": "user", "content": "What's my name?"})
r2 = client.chat.completions.create(model=MODEL, messages=messages)
answer2 = r2.choices[0].message.content
print("Bot:", answer2)   # "Your name is Tanya." ✅
messages.append({"role": "assistant", "content": answer2})

