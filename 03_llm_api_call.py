"""
The SAME chatbot, but the model runs LOCALLY via Ollama.
No API key. No internet needed. 100% private and free.
Prereqs: Ollama installed + `ollama pull llama3.2` done.
"""
from openai import OpenAI

# 1) Point the client at your LOCAL Ollama 'house' instead of the cloud.
#    api_key is required by the library but Ollama ignores it - any text works.
client = OpenAI(
    base_url="http://127.0.0.1:11434/v1",
    api_key="ollama",
)

MODEL = "llama3.2:3b"   # must match a model you pulled

# 2) Same notebook (memory) as Project 1
messages = [
    {"role": "system", "content": "You are a friendly, concise assistant."}
]

print("🦙 Local Ollama Chatbot ready (running on YOUR machine)! Type 'quit' to leave.\n")

# 3) Same forever-loop as Project 1
while True:
    user_input = input("You: ").strip()
    if user_input.lower() in ("quit", "exit", "bye"):
        print("Bot: Goodbye! 👋")
        break
    if not user_input:
        continue

    messages.append({"role": "user", "content": user_input})

    response = client.chat.completions.create(
        model=MODEL,
        messages=messages,
        temperature=0.7,
    )
    reply = response.choices[0].message.content

    print(f"Bot: {reply}\n")
    messages.append({"role": "assistant", "content": reply})

