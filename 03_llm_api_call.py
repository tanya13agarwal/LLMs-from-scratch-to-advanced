"""

Module 3 - Step 2: Call the LLM the RAW way - no SDK, just HTTP (BRUTE FORCE).

This shows what EVERY 'AI library' is secretly doing under the hood.

"""

import os
import json
import requests

# 1) Load the secret api key

# 2) The window's address (where we slide the note)
url = "https://api.groq.com/openai/v1/chat/completions"

# 3) The ENVELOPE: who we are + what we're sending
headers = {
    "Authorization": f"Bearer {api_key}",
    "Content-Type": "application/json",
}

# 4) The LETTER: our actual order (the messages list + settings)

payload = {
    "model": "llama-3.3-70b-versatile",
    "messages": [
        {"role": "system", "content": "You are a helpful assistant."},
        {"role": "user",   "content": "In one sentence, what is an API?"},
    ],
    "temperature": 0.7,
}

# 5) Slide the note through the window
response = requests.post(url, headers=headers, json=payload)

# 6) Look at the FULL raw reply the server sent back
print("=== FULL RAW RESPONSE ===")
print(json.dumps(response.json(), indent=2))

# 7) Dig out just the answer text
data = response.json()
print("\n=== JUST THE ANSWER ===")
print(data["choices"][0]["message"]["content"])

# 8) The server even tells us our token usage
print("\n=== TOKENS USED ===")
print(data["usage"])

