"""
Streaming - get the answer word-by-word as it's written.
Runs FREE on Groq.
"""
import os
from groq import Groq

client = Groq(api_key=os.environ["GROQ_API_KEY"])
MODEL = "llama-3.3-70b-versatile"
PROMPT = "Write a short, upbeat paragraph about learning to code."

# ---------- THE NORMAL WAY: wait for the whole answer, then print ----------
print("=== NON-STREAMING (you wait... then it all appears at once) ===")
resp = client.chat.completions.create(
    model=MODEL,
    messages=[{"role": "user", "content": PROMPT}],
)
print(resp.choices[0].message.content)

# ---------- STREAMING: print each piece the instant it arrives ----------
print("\n=== STREAMING (words flow in live) ===")
stream = client.chat.completions.create(
    model=MODEL,
    messages=[{"role": "user", "content": PROMPT}],
    stream=True,                       # <-- the ONLY new setting
)

for chunk in stream:
    # print(f"{chunk}\n")
    piece = chunk.choices[0].delta.content or ""
    print(piece, end="", flush=True)
print()   # final newline

"""### Function Calling"""

"""
Function calling - the AI asks US to run real code.
Runs FREE on Groq.
"""
import os
import json
from groq import Groq

client = Groq(api_key=os.environ["GROQ_API_KEY"])
MODEL = "llama-3.3-70b-versatile"

# 1) OUR REAL TOOL: an ordinary Python function (our fake "database")
FAKE_DB = {"alice": 1240.50, "bob": 89.00, "carol": 5300.75}

def get_account_balance(user_id):
    balance = FAKE_DB.get(user_id.lower())
    if balance is None:
        return f"No account found for '{user_id}'."
    return f"{user_id}'s balance is ${balance:.2f}"

# 2) DESCRIBE the tool to the model (so it knows the bell exists + how to ring it)
tools = [
    {
        "type": "function",
        "function": {
            "name": "get_account_balance",
            "description": "Get the current account balance for a given user id.",
            "parameters": {
                "type": "object",
                "properties": {
                    "user_id": {
                        "type": "string",
                        "description": "The user's id, e.g. 'alice'",
                    }
                },
                "required": ["user_id"],
            },
        },
    }
]

# 3) The user's question + the tool menu (the notebook starts here)
messages = [{"role": "user", "content": "What is Alice's account balance?"}]

# ----- TRIP 1: the wizard will REQUEST a tool, not answer -----
response = client.chat.completions.create(
    model=MODEL,
    messages=messages,
    tools=tools,                      # <-- hand over the menu of bells
)
reply = response.choices[0].message
print(f"reply:------------{reply}\n\n\n")
messages.append(reply)                # add the wizard's tool-request to the notebook

# 4) Did the wizard ring a bell?
if reply.tool_calls:
    for call in reply.tool_calls:
        fn_name = call.function.name
        args = json.loads(call.function.arguments)   # args arrive as JSON text
        print(f"🔔 Model wants to call: {fn_name}({args})")

        # 5) WE run the real Python function
        result = get_account_balance(**args)
        print(f"🛠️  Tool result: {result}")

        # 6) Hand the result back to the wizard (role 'tool')
        messages.append({
            "role": "tool",
            "tool_call_id": call.id,
            "content": result,
        })

    # ----- TRIP 2: now the wizard answers using the tool result -----
    final = client.chat.completions.create(model=MODEL, messages=messages)
    print("\n🤖 Final answer:", final.choices[0].message.content)
else:
    print("🤖 Answer (no tool needed):", reply.content)

