"""
The knobs (parameters) beyond temperature.
Runs FREE on Groq - identical to OpenAI's API.
"""
import os
from groq import Groq

client = Groq(api_key=os.environ["GROQ_API_KEY"])
MODEL = "llama-3.3-70b-versatile"

# A small reusable helper so we don't repeat the whole call each time
def ask(label, prompt, **kwargs):
    print(f"\n===== {label} =====")
    resp = client.chat.completions.create(
        model=MODEL,
        messages=[{"role": "user", "content": prompt}],
        **kwargs,            # <-- the knobs get passed in here
    )
    print(resp.choices[0].message.content)
    print(f"(completion tokens: {resp.usage.completion_tokens})")

# 1) max_tokens - hard ceiling on answer length (it CHOPS, mid-sentence if needed)
ask("max_tokens = 25 (gets cut off)",
    "Write a detailed paragraph about why the ocean matters.",
    max_tokens=25)

# 2) stop - the model halts the instant it would write '5'
ask("stop = ['5'] (counting stops around 5)",
    "Count from 1 to 10, one number per line.",
    stop=["5"])

# 3) seed - fixes the dice. Run this FILE twice; this answer should match both times.
ask("seed = 42, temperature = 0.8 (RUN TWICE, compare)",
    "Invent a quirky name for a coffee shop.",
    temperature=0.8, seed=42)

