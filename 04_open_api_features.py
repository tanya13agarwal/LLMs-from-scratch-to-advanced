"""
Structured outputs - make the model return clean JSON.
Runs FREE on Groq.
"""
import os
import json
from groq import Groq
from pydantic import BaseModel

client = Groq(api_key=os.environ["GROQ_API_KEY"])
MODEL = "llama-3.3-70b-versatile"

TEXT = "Tanvi Yadav is 25 years old and works as a data analyst in Delhi."

# ===== 1) BRUTE FORCE: ask nicely, hope for the best (often messy) =====
print("===== 1) BRUTE FORCE =====")
resp = client.chat.completions.create(
    model=MODEL,
    messages=[{"role": "user",
               "content": f"Give me JSON with name, age, job, city for: {TEXT}"}],
)
print(resp.choices[0].message.content)
print("(^ may have ```json fences or a 'Sure, here...' preamble - fragile)\n")

# ===== 2) JSON MODE: forces the WHOLE reply to be valid JSON =====
print("===== 2) JSON MODE =====")
resp = client.chat.completions.create(
    model=MODEL,
    messages=[
        {"role": "system", "content": "You output ONLY valid JSON, no extra text."},
        {"role": "user",
         "content": f"Extract keys name, age, job, city as JSON from: {TEXT}"},
    ],
    response_format={"type": "json_object"},     # <-- the magic switch
)
raw = resp.choices[0].message.content
print(raw)
data = json.loads(raw)                  # parses cleanly - nothing to strip
print("Parsed -> name:", data["name"], "| city:", data["city"], "\n")

# ===== 3) PYDANTIC: define + enforce the exact shape =====
print("===== 3) PYDANTIC =====")
class Person(BaseModel):
    name: str
    age: int        # forces a number, even if the model sent "25" as text
    job: str
    city: str

person = Person(**data)                 # validates + converts; errors loudly if wrong
print("Validated ->", person)
print("Safe to use ->", person.name, "is", person.age, "years old.")

